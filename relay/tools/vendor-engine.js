// Saves the live site's engine to src/engine.vendored.js: the fallback the relay uses when
// spelunkr.tv can't be reached or its bundle changes shape so extraction fails.
import fs from 'node:fs';
import { fetchEngineSource, loadEngine } from '../src/extract.js';

const { build, source, maxEngine } = await fetchEngineSource();
loadEngine(source); // throws if the slice doesn't evaluate
const header = `// Generated by tools/vendor-engine.js from https://spelunkr.tv${build} on ${new Date().toISOString()}.\n` +
  `// Spelunkr's own scheduling code (minified), kept as a fallback. Do not edit; re-run the tool.\n` +
  `export const BUILD = ${JSON.stringify(build)};\nexport const MAX_ENGINE = ${maxEngine};\n`;
fs.writeFileSync(new URL('../src/engine.vendored.js', import.meta.url),
  header + `export const SOURCE = ${JSON.stringify(source)};\n`);
console.log(`vendored engine from ${build} (${source.length} bytes, engine <= ${maxEngine})`);
